console.log("----------Bài 1 : Tạo một đối tượng car ----------");
let car = {
    make: "Toyota",
    model: "Crown",
    year: 2020
};
//Thêm một thuộc tính mới là color với giá trị "red"
car.color = "red";
console.log("Đối tượng car sau khi thêm thuộc tính color:");
//Cập nhật giá trị của thuộc tính year thành 2022
car.year = 2022;
console.log("Đối tượng car sau khi cập nhật thuộc tính year:");
console.log(car);
